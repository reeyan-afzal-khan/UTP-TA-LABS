def write_python(script: dict, lec, log=print) -> Path | None:
    """Write <name>.py from the script, unless you have edited it (then it is left alone)."""
    path = lec.video.with_suffix(".py")
    text = to_python(script, lec)
    if path.exists():
        current = path.read_text(encoding="utf-8")
        if not fingerprint_ok(current):
            return None
        if current == text:
            return path
    path.write_text(text, encoding="utf-8")
    log(f"  wrote {path.relative_to(path.parents[2]).as_posix()}")
    return path


def edited_python(lec) -> Path | None:
    """The lecture's .py when you have edited it."""
    path = lec.video.with_suffix(".py")
    if path.exists() and not fingerprint_ok(path.read_text(encoding="utf-8")):
        return path
    return None


def load_video_class(path: str | Path):
    """The Lecture subclass a lecture .py defines (imported by path, without running its main)."""
    import importlib.util
    import sys
    path = Path(path).resolve()
    name = "utp_lecture_" + re.sub(r"\W", "_", path.stem)
    if name in sys.modules:
        mod = sys.modules[name]
    else:
        spec = importlib.util.spec_from_file_location(name, path)
        mod = importlib.util.module_from_spec(spec)
        sys.modules[name] = mod
        spec.loader.exec_module(mod)
    from .kit import Lecture
    for obj in vars(mod).values():
        if isinstance(obj, type) and issubclass(obj, Lecture) and obj is not Lecture:
            return obj
    raise SystemExit(f"{path.name} defines no Lecture class")

